OPENMOJI_BASE = "https://raw.githubusercontent.com/hfg-gmuend/openmoji/master/color/618x618"

def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    img_dir = os.path.join(root, "images", "everyday")
    os.makedirs(img_dir, exist_ok=True)

    manifest = []
    for i, (he, tr, ru, cp, cat) in enumerate(WORDS, start=1):
        name = f"N{i:03d}.png"
        path = os.path.join(img_dir, name)
        has_image = False
        if cp:
            if os.path.exists(path) and os.path.getsize(path) > 200:
                has_image = True
            else:
                url = f"{OPENMOJI_BASE}/{cp}.png"
                try:
                    req = urllib.request.Request(url, headers={'User-Agent':'hebrew-quiz-bot/1.0'})
                    with urllib.request.urlopen(req, timeout=20) as r:
                        data = r.read()
                    with open(path, 'wb') as f:
                        f.write(data)
                    has_image = True
                    print(f"N{i:03d}  {cp}  {ru:14s} -> {len(data)} B", flush=True)
                except (urllib.error.URLError, urllib.error.HTTPError) as e:
                    print(f"FAIL N{i:03d}  {cp}  {ru}: {e}", flush=True)
        manifest.append({
            "n": i,
            "he": he,
            "tr": tr,
            "ru": ru,
            "cat": cat,
            "img": has_image,
        })

    with open(os.path.join(img_dir, "_index.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    print(f"\nManifest: {os.path.join(img_dir, '_index.json')}")
    print(f"Images present: {sum(1 for m in manifest if m['img'])}/{len(manifest)}")

if __name__ == "__main__":
    main()
