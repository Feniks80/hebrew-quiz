def parse_b2():
    """Return {category_name: [[ru, he, translit], ...], ...} from B2."""
    src = open(B2_PATH, encoding="utf-8").read()
    m = re.search(r"const Q=(\[.*?\]);", src, re.S)
    data = json.loads(m.group(1))
    return {name: rows for name, rows in data}

def normalize(s: str) -> str:
    s = s.lower().strip()
    s = re.sub(r"[«»\"'`!?.,;:()\[\]]", "", s)
    s = re.sub(r"\s+", " ", s)
    return s

def emoji_for(ru: str):
    """Return codepoint hex or None."""
    n = normalize(ru)
    if n in EMOJI_MAP and EMOJI_MAP[n]:
        return EMOJI_MAP[n]
    # try first word only
    first = n.split(" ")[0]
    if first != n and first in EMOJI_MAP and EMOJI_MAP[first]:
        return EMOJI_MAP[first]
    return None

def fetch_icon(cp: str) -> bool:
    """Download OpenMoji icon for a codepoint if not already present."""
    if not cp:
        return False
    path = os.path.join(IMG_DIR, f"{cp}.png")
    if os.path.exists(path) and os.path.getsize(path) > 200:
        return True
    os.makedirs(IMG_DIR, exist_ok=True)
    url = f"{OPENMOJI_BASE}/{cp}.png"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "hebrew-quiz-bot/1.0"})
        with urllib.request.urlopen(req, timeout=20) as r:
            data = r.read()
        with open(path, "wb") as f:
            f.write(data)
        return True
    except Exception as e:
        print(f"  fetch FAIL {cp}: {e}")
        # Make sure we don't keep a half-file
        if os.path.exists(path):
            try: os.remove(path)
            except: pass
        return False

def build_block(block, b2):
    seen = set()
    words = []  # [(he, tr, ru, cp_or_None, cat_label)]
    for cat_label, subdeck_names in block["groups"]:
        for sd in subdeck_names:
            if sd not in b2:
                print(f"  WARN: B2 sub-deck not found: {sd!r}")
                continue
            for ru, he, tr in b2[sd]:
                if he in seen:
                    continue
                seen.add(he)
                cp = emoji_for(ru)
                words.append((he, tr, ru, cp, cat_label))
                if len(words) >= block["limit"]:
                    break
            if len(words) >= block["limit"]:
                break
        if len(words) >= block["limit"]:
            break

    # Fetch icons for all unique codepoints
    cps = sorted({w[3] for w in words if w[3]})
    print(f"  {len(words)} words, {len(cps)} unique icons needed")
    have = 0
    for cp in cps:
        if fetch_icon(cp):
            have += 1
    print(f"  icons present: {have}/{len(cps)}")

    # Re-check: drop cp if file is missing (download failed)
    cleaned = []
    for he, tr, ru, cp, cat in words:
        if cp and not os.path.exists(os.path.join(IMG_DIR, f"{cp}.png")):
            cp = None
        cleaned.append([he, tr, ru, cp, cat])

    # Render template
    template = open(TEMPLATE_PATH, encoding="utf-8").read()
    words_json = "[\n" + ",\n".join(
        "  " + json.dumps(w, ensure_ascii=False) for w in cleaned
    ) + "\n]"
    html = (template
        .replace("__TITLE__", block["title"])
        .replace("__HEADING__", block["heading"])
        .replace("__SUBTITLE__", block["subtitle"])
        .replace("__STORAGE_KEY__", f"he-block-{block['id']}")
        .replace("__WORDS_DATA__", words_json))
    out_path = os.path.join(ROOT, f"hebrew-{block['id']}.html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)
    have_img = sum(1 for w in cleaned if w[3])
    print(f"  → {out_path}  ({len(cleaned)} words, {have_img} with icon)")

def main():
    targets = sys.argv[1:] or [b["id"] for b in BLOCKS]
    b2 = parse_b2()
    for block in BLOCKS:
        if block["id"] not in targets:
            continue
        print(f"\n=== {block['id']} ===")
        build_block(block, b2)

if __name__ == "__main__":
    main()
